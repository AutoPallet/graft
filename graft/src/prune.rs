//! Per-`.o` pruning for overlay mode.
//!
//! Given a source object and the set of its sections the closure wants to
//! keep, rewrite it as a minimal ELF object retaining:
//!   - Only closure-member sections (drop everything else).
//!   - Symbols defined in kept sections (unchanged).
//!   - Symbols whose defining section was pruned, rewritten as UND:
//!     * globals → UND with the same name; `base_symbols.ld` PROVIDEs it.
//!     * locals → renamed to `<name>@<tu_id_hex>`, scope bumped to GLOBAL
//!       UND; same linker-script PROVIDE resolves them against base.
//!   - Relocations from kept sections, retargeted through the new symbol
//!     table.
//!
//! This is `object::write::Object` driven — much shorter than hand-rolling
//! an ELF writer, and correct for the narrow slice (ET_REL, SHT_PROGBITS
//! / SHT_NOBITS sections) rustc emits.

use std::collections::{HashMap, HashSet};

use anyhow::{Context, Result, anyhow, bail};
use object::{
    Architecture, BinaryFormat, Endianness, Object, ObjectSection, ObjectSymbol,
    RelocationFlags, RelocationTarget, SectionIndex, SectionKind, SymbolIndex, SymbolKind,
    SymbolScope,
    elf::R_X86_64_NONE,
    write::{
        self, Object as WObject, Relocation as WRelocation, SectionId, Symbol as WSymbol,
        SymbolId, SymbolSection as WSymbolSection,
    },
};

/// Result of pruning one source `.o`.
pub struct Pruned {
    pub bytes: Vec<u8>,
    pub kept_sections: usize,
    pub renamed_locals: usize,
}

/// Prune `source_bytes` (a single `.o` file) against `keep`, the set of
/// 0-based indexes (matching `ParsedObject::sections`) that the closure
/// wants included.
pub fn prune_object(
    source_bytes: &[u8],
    source_tu_id: [u8; 8],
    keep: &HashSet<u32>,
) -> Result<Pruned> {
    let src = object::File::parse(source_bytes).context("parse source .o")?;

    let arch = match src.architecture() {
        object::Architecture::X86_64 => Architecture::X86_64,
        a => bail!("unsupported architecture {a:?}"),
    };
    let endian = if src.is_little_endian() {
        Endianness::Little
    } else {
        Endianness::Big
    };

    let mut out = WObject::new(BinaryFormat::Elf, arch, endian);

    // object::read section indexes are 1-based; our `keep` indexes are
    // 0-based (how ParsedObject numbers them).
    let is_kept = |idx: SectionIndex| keep.contains(&(idx.0 as u32).saturating_sub(1));

    // Pass 1: add kept sections.
    let mut sec_map: HashMap<SectionIndex, SectionId> = HashMap::new();
    for src_sec in src.sections() {
        let idx = src_sec.index();
        if !is_kept(idx) {
            continue;
        }
        let kind = src_sec.kind();
        let new_id = out.add_section(
            Vec::new(),
            src_sec.name().unwrap_or("").as_bytes().to_vec(),
            kind,
        );
        {
            let w_sec = out.section_mut(new_id);
            let align = src_sec.align().max(1);
            if kind.is_bss() {
                w_sec.append_bss(src_sec.size(), align);
            } else {
                let data = src_sec.data().unwrap_or(&[]).to_vec();
                w_sec.set_data(data, align);
            }
        }
        sec_map.insert(idx, new_id);
    }

    // Pass 2: add symbols.
    //
    // A symbol in the output is one of:
    //   - Defined in a kept section: copy scope + name + value.
    //   - Pruned-local definition: rename to `<name>@<tu_hex>` with
    //     GLOBAL UND; reference resolves via base_symbols.ld PROVIDE.
    //   - Pruned-global definition or already-UND: GLOBAL UND, same name.
    //
    // STT_SECTION and STT_FILE symbols are regenerated by the writer.
    let mut sym_map: HashMap<SymbolIndex, SymbolId> = HashMap::new();
    let mut renamed_locals: usize = 0;
    let tu_hex: String = source_tu_id.iter().map(|b| format!("{b:02x}")).collect();

    for src_sym in src.symbols() {
        let kind = src_sym.kind();
        if matches!(kind, SymbolKind::File | SymbolKind::Section) {
            continue;
        }

        let name = src_sym.name().unwrap_or("").to_string();
        let section_idx = src_sym.section_index();
        let is_weak = src_sym.is_weak();
        let is_local = matches!(src_sym.scope(), SymbolScope::Compilation | SymbolScope::Unknown);

        // Classify by whether the symbol has a defining section, not by
        // `is_definition()` — that returns false for STT_NOTYPE locals
        // like `.LC0`, which we still need to rewrite through the
        // kept/pruned logic.
        let (final_name, final_scope, final_section) = match section_idx {
            Some(idx) if sec_map.contains_key(&idx) => {
                // Defined in a kept section: preserve.
                let scope = if is_local {
                    write::SymbolScope::Compilation
                } else {
                    write::SymbolScope::Dynamic
                };
                (name.clone(), scope, WSymbolSection::Section(sec_map[&idx]))
            }
            Some(_) => {
                // Defined in a pruned section. Emit as UND; rename locals
                // so base_symbols.ld PROVIDEs can target them by tu_hex.
                if is_local && !name.is_empty() {
                    renamed_locals += 1;
                    (
                        format!("{name}@{tu_hex}"),
                        write::SymbolScope::Dynamic,
                        WSymbolSection::Undefined,
                    )
                } else {
                    (name.clone(), write::SymbolScope::Dynamic, WSymbolSection::Undefined)
                }
            }
            None => {
                // Already UND, absolute, or common. Pass through as UND
                // global — base PROVIDEs supply the address.
                (name.clone(), write::SymbolScope::Dynamic, WSymbolSection::Undefined)
            }
        };

        let value = match final_section {
            WSymbolSection::Section(_) => src_sym.address(),
            _ => 0,
        };

        let wsym = WSymbol {
            name: final_name.into_bytes(),
            value,
            size: src_sym.size(),
            kind: map_kind(kind),
            scope: final_scope,
            weak: is_weak,
            section: final_section,
            flags: write::SymbolFlags::None,
        };
        let id = out.add_symbol(wsym);
        sym_map.insert(src_sym.index(), id);
    }

    // Cache of (pruned section idx) → (surrogate symbol id, its offset
    // in the section). Used to rewrite section-symbol relocs that target
    // pruned sections into named-symbol relocs with an adjusted addend.
    // Populated lazily.
    let mut pruned_surrogate: HashMap<SectionIndex, (SymbolId, u64)> = HashMap::new();

    // Pass 3: relocations from kept sections.
    for src_sec in src.sections() {
        let Some(&new_sec_id) = sec_map.get(&src_sec.index()) else {
            continue;
        };
        for (offset, r) in src_sec.relocations() {
            let r_type = match r.flags() {
                RelocationFlags::Elf { r_type } => r_type,
                _ => continue,
            };
            if r_type == R_X86_64_NONE {
                continue;
            }

            let mut addend_adjust: i64 = 0;
            let new_sym_id = match r.target() {
                RelocationTarget::Symbol(sidx) => {
                    if let Some(&id) = sym_map.get(&sidx) {
                        id
                    } else {
                        // STT_SECTION symbol not in sym_map.
                        let src_sym = src
                            .symbol_by_index(sidx)
                            .map_err(|e| anyhow!("resolve reloc target: {e}"))?;
                        let Some(target_sec_idx) = src_sym.section_index() else {
                            bail!(
                                "STT_SECTION symbol with no section in {}",
                                src_sec.name().unwrap_or("?")
                            );
                        };
                        if let Some(&target_new_id) = sec_map.get(&target_sec_idx) {
                            out.section_symbol(target_new_id)
                        } else {
                            let (sym, off) = surrogate_for_pruned_section(
                                &src,
                                target_sec_idx,
                                &sym_map,
                                &mut pruned_surrogate,
                                src_sec.name().unwrap_or("?"),
                            )?;
                            addend_adjust = -(off as i64);
                            sym
                        }
                    }
                }
                RelocationTarget::Section(target_sec_idx) => {
                    if let Some(&target_new_id) = sec_map.get(&target_sec_idx) {
                        out.section_symbol(target_new_id)
                    } else {
                        let (sym, off) = surrogate_for_pruned_section(
                            &src,
                            target_sec_idx,
                            &sym_map,
                            &mut pruned_surrogate,
                            src_sec.name().unwrap_or("?"),
                        )?;
                        addend_adjust = -(off as i64);
                        sym
                    }
                }
                RelocationTarget::Absolute => {
                    bail!("absolute reloc target not supported");
                }
                other => bail!("unsupported reloc target {other:?}"),
            };

            out.add_relocation(
                new_sec_id,
                WRelocation {
                    offset,
                    symbol: new_sym_id,
                    addend: r.addend() + addend_adjust,
                    flags: RelocationFlags::Elf { r_type },
                },
            )
            .with_context(|| format!("add reloc at {offset:#x} in {}", src_sec.name().unwrap_or("?")))?;
        }
    }

    let bytes = out.write().map_err(|e| anyhow!("write pruned object: {e}"))?;
    Ok(Pruned {
        bytes,
        kept_sections: sec_map.len(),
        renamed_locals,
    })
}

fn map_kind(k: SymbolKind) -> SymbolKind {
    // object::write rejects `Unknown` for defined symbols, but rustc emits
    // STT_NOTYPE for local labels like `.LC0` / `.LCPI0_0`. Map those to
    // `Label`, which also serializes to STT_NOTYPE.
    match k {
        SymbolKind::Unknown => SymbolKind::Label,
        other => other,
    }
}

/// Find a named symbol defined in `target_sec_idx` to act as a surrogate
/// when a reloc targets the section itself (STT_SECTION) or targets a
/// section that was pruned away. Returns the surrogate's new SymbolId and
/// its address within the source section, so the caller can subtract that
/// address from the reloc addend (reloc now resolves to `surrogate + (orig
/// - surrogate_addr)`, equivalent to the original `section + orig`).
fn surrogate_for_pruned_section(
    src: &object::File<'_>,
    target_sec_idx: SectionIndex,
    sym_map: &HashMap<SymbolIndex, SymbolId>,
    cache: &mut HashMap<SectionIndex, (SymbolId, u64)>,
    from_section_name: &str,
) -> Result<(SymbolId, u64)> {
    if let Some(&hit) = cache.get(&target_sec_idx) {
        return Ok(hit);
    }
    // Prefer the lowest-address named definition. For rustc's
    // `.text.<mangle>` / `.rodata.<mangle>` sections that's the function
    // or static that gives the section its name — and since that symbol
    // is in sym_map as a UND (defining section was pruned), it'll resolve
    // via base_symbols.ld PROVIDE back to the base's address.
    let mut best: Option<(u64, SymbolIndex)> = None;
    for sym in src.symbols() {
        if sym.section_index() != Some(target_sec_idx) {
            continue;
        }
        if matches!(sym.kind(), SymbolKind::File | SymbolKind::Section) {
            continue;
        }
        if sym.name().unwrap_or("").is_empty() {
            continue;
        }
        let addr = sym.address();
        if best.map_or(true, |(b, _)| addr < b) {
            best = Some((addr, sym.index()));
        }
    }
    let (off, sidx) = best.ok_or_else(|| {
        anyhow!(
            "reloc from {from_section_name} targets pruned section #{} with no named definition to retarget through",
            target_sec_idx.0,
        )
    })?;
    let sym_id = *sym_map.get(&sidx).ok_or_else(|| {
        anyhow!(
            "surrogate symbol {sidx:?} for pruned section #{} missing from sym_map",
            target_sec_idx.0
        )
    })?;
    cache.insert(target_sec_idx, (sym_id, off));
    Ok((sym_id, off))
}

/// Predicate helper: true if this section kind should be carried into
/// the pruned object (as opposed to things like metadata sections).
pub fn kept_section_kind(kind: SectionKind) -> bool {
    matches!(
        kind,
        SectionKind::Text
            | SectionKind::Data
            | SectionKind::ReadOnlyData
            | SectionKind::ReadOnlyString
            | SectionKind::UninitializedData
            | SectionKind::Tls
            | SectionKind::UninitializedTls
    )
}
